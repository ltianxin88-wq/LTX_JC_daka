import assert from 'node:assert/strict'
import test from 'node:test'
import { readFile } from 'node:fs/promises'

test('local API permits reads and scoped configuration updates with a same-origin client marker', async () => {
  const source = await readFile(new URL('../src/api.ts', import.meta.url), 'utf8')
  assert.match(source, /CLIENT_HEADER/)
  assert.match(source, /'snapshot'/)
  assert.match(source, /path === 'configuration' && method === 'PUT'/)
  assert.match(source, /path === 'personal-attendance' && method === 'GET'/)
  assert.match(source, /path === 'personal-account' && method === 'PUT'/)
  assert.match(source, /path === 'personal-automation' && method === 'GET'/)
  assert.match(source, /path === 'personal-makeup' && method === 'GET'/)
  assert.match(source, /path === 'personal-run' && method === 'POST'/)
  assert.match(source, /path === 'management-run' && method === 'POST'/)
  assert.match(source, /path === 'management-log' && method === 'GET'/)
  assert.match(source, /path === 'personal-schedule' && method === 'PUT'/)
  assert.match(source, /path === 'personal-makeup' && method === 'POST'/)
  assert.match(source, /path === 'roster' && method === 'GET'/)
  assert.match(source, /path === 'roster' && method === 'PUT'/)
  assert.match(source, /path === 'personal-roster' && method === 'GET'/)
  assert.match(source, /path === 'personal-roster' && method === 'PUT'/)
  assert.match(source, /validateConfigurationUpdate/)
  assert.match(source, /validatePersonalAccountUpdate/)
  assert.match(source, /validatePersonalScheduleUpdate/)
  assert.match(source, /validatePersonalMakeupSubmit/)
  assert.match(source, /validateRosterUpdate/)
  assert.match(source, /validatePersonalRosterUpdate/)
  assert.match(source, /16 \* 1024/)
  assert.match(source, /512 \* 1024/)
  assert.doesNotMatch(source, /child_process|exec\(/)
})
